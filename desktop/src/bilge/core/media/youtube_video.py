"""A YouTube video's id from an address, its caption tracks from YouTube's player answer, the track to read, and
the caption file as plain text."""

import contextlib
import html
import re
from dataclasses import dataclass
from typing import Any
from urllib.parse import parse_qsl, urlencode, urlsplit, urlunsplit
from xml.parsers import expat

_ID = r"([A-Za-z0-9_-]{11})(?![A-Za-z0-9_-])"
_ADDRESS = re.compile(
    r"(?:https?://)?(?:(?:www|m|music)\.)?(?:youtube(?:-nocookie)?\.com/(?:watch\?(?:\S*?&)?v=|shorts/|embed/|live/|v/)"
    r"|youtu\.be/)" + _ID,
    re.IGNORECASE,
)


def video_id(text: str) -> str | None:
    """From the first YouTube address in the text: watch, youtu.be, shorts, embed and live links."""
    found = _ADDRESS.search(text or "")
    return found.group(1) if found else None


@dataclass(frozen=True)
class Track:
    language: str
    # Generated by speech recognition rather than written by someone.
    automatic: bool
    url: str


@dataclass(frozen=True)
class Video:
    title: str
    playable: bool
    tracks: tuple[Track, ...]


def video(player: Any) -> Video:
    """YouTube's player answer; anything missing reads as no title, not playable or no captions."""
    details, status = _dict(player, "videoDetails"), _dict(player, "playabilityStatus")
    renderer = _dict(_dict(player, "captions"), "playerCaptionsTracklistRenderer")
    entries = renderer.get("captionTracks")
    tracks = []
    for entry in entries if isinstance(entries, list) else []:
        if not isinstance(entry, dict):
            continue
        url, language = str(entry.get("baseUrl") or ""), str(entry.get("languageCode") or "")
        host = urlsplit(url).hostname or ""
        if urlsplit(url).scheme == "https" and (host == "youtube.com" or host.endswith(".youtube.com")) and language:
            tracks.append(Track(language, entry.get("kind") == "asr", _plain_format(url)))
    return Video(str(details.get("title") or ""), status.get("status") == "OK", tuple(tracks))


def _dict(value: Any, key: str) -> dict:
    found = value.get(key) if isinstance(value, dict) else None
    return found if isinstance(found, dict) else {}


def _plain_format(url: str) -> str:
    """Without `fmt`, the caption service answers in its simplest XML (<text> elements)."""
    parts = urlsplit(url)
    query = [(key, value) for key, value in parse_qsl(parts.query, keep_blank_values=True) if key != "fmt"]
    return urlunsplit(parts._replace(query=urlencode(query)))


def choose(tracks: tuple[Track, ...], preferred: str) -> Track | None:
    """In the preferred language, written before generated; else in the language the video speaks (that of its
    generated track); else English; else whatever there is."""

    def base(track: Track) -> str:
        return track.language.split("-")[0].lower()

    spoken = next((base(track) for track in tracks if track.automatic), None)
    for language in dict.fromkeys(filter(None, (preferred, spoken, "en"))):
        for automatic in (False, True):
            found = next((t for t in tracks if base(t) == language and t.automatic == automatic), None)
            if found is not None:
                return found
    return next((t for t in tracks if not t.automatic), tracks[0] if tracks else None)


def transcript(data: bytes) -> str:
    """The caption file's text in one piece: the simple format (<text>) and the timed one (<p> with <s> words)."""
    lines: list[str] = []
    current: list[str] | None = None

    def start(name: str, _: dict[str, str]) -> None:
        nonlocal current
        if name in ("text", "p"):
            current = []

    def characters(text: str) -> None:
        if current is not None:
            current.append(text)

    def end(name: str) -> None:
        nonlocal current
        if name in ("text", "p") and current is not None:
            # The simple format escapes twice: "&amp;#39;" arrives as "&#39;".
            line = " ".join(html.unescape("".join(current)).split())
            if line:
                lines.append(line)
            current = None

    parser = expat.ParserCreate()
    parser.StartElementHandler = start
    parser.CharacterDataHandler = characters
    parser.EndElementHandler = end
    with contextlib.suppress(expat.ExpatError):
        parser.Parse(data, True)
    return " ".join(lines)
